package.path="./?.lua;./?/init.lua;"..package.path
local M=require("src.model")
local s=M.new()
assert(s.page=="title")
M.openGallery(s)
assert(s.page=="gallery")
M.openNewCanvas(s)
assert(s.modal=="newCanvas")
assert(M.createCanvas(s)==true)
assert(s.page=="editor")
assert(#s.works==1)
assert(#s.layers==1)
assert(M.setTool(s,"Brush"))
assert(s.panel=="brush")
assert(M.setBrush(s,2))
assert(s.brush==2)
M.setBrushOpacity(s,200)
assert(s.brushOpacity==100)
M.addLayer(s)
assert(#s.layers==2)
M.duplicateLayer(s)
assert(#s.layers==3)
M.setBlend(s,"Multiply")
assert(s.layers[1].blend=="Multiply")
M.setLayerOpacity(s,47)
assert(s.layers[1].opacity==47)
M.deleteLayer(s)
assert(#s.layers==2)
M.setColor(s,.3,.5,.8)
assert(s.color[2]==.5)
M.setZoom(s,1000)
assert(s.zoom==800)
M.back(s)
assert(s.panel==nil)
M.back(s)
assert(s.page=="gallery")
assert(M.openWork(s,1))
assert(s.page=="editor")
print("model tests: OK")
